function getStoredData(key, fallback) {
  try {
    const item = localStorage.getItem("gramkushal_" + key);
    return item ? JSON.parse(item) : fallback;
  } catch (e) {
    return fallback;
  }
}

function setStoredData(key, value) {
  try {
    localStorage.setItem("gramkushal_" + key, JSON.stringify(value));
  } catch (e) {
    console.error("Storage error:", e);
  }
}

